/**
 * Generates backend/src/main/resources/db/seed.sql from the shipped TypeScript
 * data files, so the database starts with exactly the content the static site
 * renders — no hand-transcription, no drift between the two.
 *
 * Usage:  node scripts/export-seed.mjs
 *
 * How it reads TypeScript: these data files are plain object literals with a
 * few type annotations, so the annotations are stripped and the remainder is
 * imported as a real ES module. Anything fancier than that fails loudly.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tmp = join(root, "node_modules", ".cache", "seed");

const stripTypes = (src) =>
  src
    .replace(/^\s*import\s+type\s[^\n]*\n/gm, "")
    .replace(/\bas\s+const\b/g, "")
    // `export const name: SomeType =` — type annotations never contain `=`,
    // so stopping at the first one lands on the assignment.
    .replace(/export\s+const\s+(\w+)\s*:\s*[^=]*?=/g, "export const $1 =");

async function load(name) {
  const file = join(tmp, `${name}.mjs`);
  writeFileSync(file, stripTypes(readFileSync(join(root, "src/data", `${name}.ts`), "utf8")));
  return import(pathToFileURL(file).href);
}

const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => (v === undefined ? "NULL" : `'${JSON.stringify(v).replace(/'/g, "''")}'`);

const { teamMembers } = await load("teamMembers");
const { projects } = await load("projects");
const { achievements } = await load("achievements");
const { technologies } = await load("technology");
const site = await load("site");

const out = [];
out.push("-- =====================================================================");
out.push("--  GENERATED by scripts/export-seed.mjs — do not edit by hand.");
out.push("--  Regenerate with:  node scripts/export-seed.mjs");
out.push(`--  Source: ${teamMembers.length} members, ${projects.length} projects,`);
out.push(`--         ${achievements.length} achievements, ${technologies.length} technologies.`);
out.push("--");
out.push("--  Idempotent: every statement is an upsert, so re-running refreshes");
out.push("--  content without duplicating rows. It never touches admin_users.");
out.push("-- =====================================================================");
out.push("");
out.push("USE fullstack_crew;");
out.push("");

out.push("-- team_members");
for (const m of teamMembers) {
  out.push(`INSERT INTO team_members
  (id, slug, name, role, specialty, accent, short_bio, biography, expanded_bio, approach,
   collaboration, photo, location, email, github_url, linkedin_url, portfolio_url,
   skills, skill_groups, featured_project_slugs, achievements, interests, strengths, sort_order)
VALUES (${q(m.id)}, ${q(m.slug)}, ${q(m.name)}, ${q(m.role)}, ${q(m.specialty)}, ${q(m.accent)},
  ${q(m.shortBio)}, ${q(m.biography)}, ${q(m.expandedBio)}, ${q(m.approach)},
  ${q(m.collaboration)}, ${q(m.photo)}, ${q(m.location)}, ${q(m.email)}, ${q(m.githubUrl)},
  ${q(m.linkedinUrl)}, ${q(m.portfolioUrl)},
  ${j(m.skills)}, ${j(m.skillGroups)}, ${j(m.featuredProjectSlugs)}, ${j(m.achievements)},
  ${j(m.interests)}, ${j(m.strengths)}, ${teamMembers.indexOf(m)})
ON DUPLICATE KEY UPDATE
  slug=VALUES(slug), name=VALUES(name), role=VALUES(role), specialty=VALUES(specialty),
  accent=VALUES(accent), short_bio=VALUES(short_bio), biography=VALUES(biography),
  expanded_bio=VALUES(expanded_bio), approach=VALUES(approach), collaboration=VALUES(collaboration),
  photo=VALUES(photo), location=VALUES(location), email=VALUES(email), github_url=VALUES(github_url),
  linkedin_url=VALUES(linkedin_url), portfolio_url=VALUES(portfolio_url), skills=VALUES(skills),
  skill_groups=VALUES(skill_groups), featured_project_slugs=VALUES(featured_project_slugs),
  achievements=VALUES(achievements), interests=VALUES(interests), strengths=VALUES(strengths),
  sort_order=VALUES(sort_order);`);
  out.push("");
}

out.push("-- projects");
for (const p of projects) {
  out.push(`INSERT INTO projects
  (slug, title, description, thumbnail, technologies, categories, contributor_ids,
   live_demo_url, github_url, featured, year, overview, problem, solution, key_features,
   contributions, screenshots, sort_order)
VALUES (${q(p.slug)}, ${q(p.title)}, ${q(p.description)}, ${q(p.thumbnail)},
  ${j(p.technologies)}, ${j(p.categories)}, ${j(p.contributorIds)},
  ${q(p.liveDemoUrl)}, ${q(p.githubUrl)}, ${p.featured ? 1 : 0}, ${q(p.year)},
  ${q(p.detail.overview)}, ${q(p.detail.problem)}, ${q(p.detail.solution)},
  ${j(p.detail.keyFeatures)}, ${j(p.detail.contributions)}, ${j(p.detail.screenshots ?? null)},
  ${projects.indexOf(p)})
ON DUPLICATE KEY UPDATE
  title=VALUES(title), description=VALUES(description), thumbnail=VALUES(thumbnail),
  technologies=VALUES(technologies), categories=VALUES(categories),
  contributor_ids=VALUES(contributor_ids), live_demo_url=VALUES(live_demo_url),
  github_url=VALUES(github_url), featured=VALUES(featured), year=VALUES(year),
  overview=VALUES(overview), problem=VALUES(problem), solution=VALUES(solution),
  key_features=VALUES(key_features), contributions=VALUES(contributions),
  screenshots=VALUES(screenshots), sort_order=VALUES(sort_order);`);
  out.push("");
}

out.push("-- achievements");
for (const a of achievements) {
  out.push(`INSERT INTO achievements (id, title, summary, kind, period, accent, member_id)
VALUES (${q(a.id)}, ${q(a.title)}, ${q(a.summary)}, ${q(a.kind)}, ${q(a.date)}, ${q(a.accent)}, ${q(a.memberId)})
ON DUPLICATE KEY UPDATE
  title=VALUES(title), summary=VALUES(summary), kind=VALUES(kind), period=VALUES(period),
  accent=VALUES(accent), member_id=VALUES(member_id);`);
  out.push("");
}

out.push("-- technologies");
for (const t of technologies) {
  out.push(`INSERT INTO technologies (name, category, description, member_ids, sort_order)
VALUES (${q(t.name)}, ${q(t.category)}, ${q(t.description)}, ${j(t.memberIds)}, ${technologies.indexOf(t)})
ON DUPLICATE KEY UPDATE
  category=VALUES(category), description=VALUES(description),
  member_ids=VALUES(member_ids), sort_order=VALUES(sort_order);`);
  out.push("");
}

const siteDocument = {
  brand: site.brand,
  navItems: site.navItems,
  cta: site.cta,
  heroHeadline: [...site.heroHeadline],
  // The hero paragraph is brand.description in the shipped data.
  heroDescription: site.heroDescription ?? site.brand.description,
  coreValues: site.coreValues,
  workflow: site.workflow,
};
out.push("-- site_content: one JSON document per editable key");
for (const [key, value] of Object.entries(siteDocument)) {
  if (value === null) continue;
  out.push(`INSERT INTO site_content (content_key, payload)
VALUES (${q(key)}, ${j(value)})
ON DUPLICATE KEY UPDATE payload=VALUES(payload);`);
}
out.push("");

const target = join(root, "backend", "src", "main", "resources", "db", "seed.sql");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out.join("\n"));
console.log(
  `[seed] wrote ${target}\n` +
    `       ${teamMembers.length} members · ${projects.length} projects · ` +
    `${achievements.length} achievements · ${technologies.length} technologies · ` +
    `${Object.keys(siteDocument).length - 1} site keys`
);

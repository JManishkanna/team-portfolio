-- Run this in the Supabase SQL editor after creating your project.
-- RLS keeps profile and skill records readable publicly but writable only by
-- authenticated users. Tighten the write policy to an admin role before launch.

create table if not exists public.team_members (
  id text primary key,
  slug text unique not null,
  name text not null,
  role text not null default '',
  short_bio text not null default '',
  biography text not null default '',
  location text not null default '',
  photo text not null default '',
  email text not null default '',
  accent text not null default '#25C7D9',
  specialty text not null default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.skills (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  description text not null default '',
  member_ids text[] not null default '{}',
  updated_at timestamptz not null default now()
);

alter table public.team_members enable row level security;
alter table public.skills enable row level security;

create policy "Public can read team members"
  on public.team_members for select using (true);

create policy "Authenticated users can manage team members"
  on public.team_members for all to authenticated using (true) with check (true);

create policy "Public can read skills"
  on public.skills for select using (true);

create policy "Authenticated users can manage skills"
  on public.skills for all to authenticated using (true) with check (true);
